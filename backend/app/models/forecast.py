import uuid
from datetime import date
from decimal import Decimal
from typing import Optional, Dict, Any
from sqlalchemy import String, Numeric, Date, Boolean, ForeignKey, JSON
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship
from app.core.database import Base
from app.models.base import UUIDMixin, TimestampMixin


class LiquidityForecast(Base, UUIDMixin, TimestampMixin):
    """
    Projected daily cash balance and flows generated by the Autonomous CFO.
    Supports running baseline forecasts and 'what-if' simulation scenarios.
    """
    __tablename__ = "liquidity_forecasts"

    account_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("bank_accounts.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )

    forecast_date: Mapped[date] = mapped_column(Date, index=True, nullable=False)
    projected_balance: Mapped[Decimal] = mapped_column(Numeric(15, 2), nullable=False)
    projected_inflows: Mapped[Decimal] = mapped_column(Numeric(15, 2), default=Decimal("0.00"), nullable=False)
    projected_outflows: Mapped[Decimal] = mapped_column(Numeric(15, 2), default=Decimal("0.00"), nullable=False)

    is_deficit: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    scenario_name: Mapped[str] = mapped_column(String(64), default="baseline", index=True, nullable=False)

    # Detailed driver breakdown (e.g. expected wages, fixed rent, predicted POS revenue)
    drivers: Mapped[Dict[str, Any]] = mapped_column(JSON, default=dict, nullable=False)

    # Relationships
    account: Mapped["BankAccount"] = relationship("BankAccount", back_populates="forecasts")
